export function Icon({ name, class: cls, style }: { name?: string | null; class?: string; style?: JSX.CSSProperties }) {
  if (!name) return null
  const Glyph = ICONS[name]
  if (!Glyph) return null
  return (
    <span class={`i ${cls ?? ''}`} style={style} aria-hidden="true">
      <Glyph strokeWidth={1.8} />
    </span>
  )
}

export function Glyph({ k }: { k: string }) {
  return <img class="btn-glyph" src={iconUrl(`buttons/${k}`)} alt={k.toUpperCase()} />
}
